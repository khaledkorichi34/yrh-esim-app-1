def save(date, slot, name, img, body, handle=None):
    ig, fb = M.caption(body, handle)
    stem = '%s-%s' % (date, slot)
    out = os.path.join(M.HERE, 'social')
    img.resize((M.W, M.H), Image.LANCZOS).save(os.path.join(out, stem + '.jpg'), quality=90)
    with open(os.path.join(out, stem + '.json'), 'w', encoding='utf-8') as fh:
        json.dump({'date': date, 'slot': slot, 'name': name, 'image': M.RAW + stem + '.jpg', 'ig': ig, 'fb': fb},
                  fh, ensure_ascii=False, indent=1)
    print(stem, name)


def q(date, title, options, intro):
    """09:00 question post: the options are numbered answers people reply with in the comments."""
    img = M.tip('سؤال اليوم', title, options)
    body = intro + '\n\n' + '\n'.join('%d. %s' % (i + 1, o) for i, o in enumerate(options)) + \
        '\n\nجاوبونا بالرقم في التعليقات 👇'
    save(date, '09', 'Question', img, body)


def edu(date, kicker, title, points, intro, handle=None):
    img = M.tip(kicker, title, points)
    body = intro + '\n\n' + '\n'.join('• ' + p for p in points)
    save(date, '15', 'Explainer', img, body, handle)


def promo(date, name, handle, title, sub, code, plans, intro):
    off = [(gb, d, '%.2f' % (float(p) * 0.7)) for gb, d, p in plans]
    img = M.offer('خصم 30% بالكود AHLAN30', title, sub, code, off)
    lines = '\n'.join('• %s · %s · €%s ← €%s بعد الخصم' % (gb, d, p, o[2]) for (gb, d, p), o in zip(plans, off))
    body = intro + '\n\n' + lines + '\n\nالأسعار بعد الخصم تقريبية وتظهر عند الدفع بالكود.'
    save(date, '19', name, img, body, handle)


def trust(date, kicker, title, points, intro, handle=None):
    img = M.tip(kicker, title, points)
    body = intro + '\n\n' + '\n'.join('• ' + p for p in points)
    save(date, '22', 'Trust', img, body, handle)


